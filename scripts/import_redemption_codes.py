#!/usr/bin/env python3
"""Hash vyšlápni.cz redemption codes and emit an INSERT for the DBA.

CSV columns: challenge_id,code,buyer_email[,expires_at]

The plaintext code is read only to compute SHA-256. The SQL on stdout
contains the hash and a 4-character hint, not the code. This script does
not connect to Postgres and does not apply anything.

  python3 scripts/import_redemption_codes.py orders.csv > redeem.sql

Ask first before running the SQL on production.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import re
import sys
from pathlib import Path

CODE = re.compile(r"^[A-Z0-9]{8,16}$")
UUID = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$",
    re.IGNORECASE,
)
VECTOR = "668c072603bbc3a89b6e2a67f878e29dbe33c020984d4928eda299e7cebe0adb"


def normalize_code(raw: str) -> str | None:
    if len(raw) > 64:
        return None
    stripped = re.sub(r"[\s-]+", "", raw.strip().upper())
    if not CODE.fullmatch(stripped):
        return None
    return stripped


def hash_code(normalized: str) -> str:
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def fold_email(raw: str) -> str | None:
    email = raw.strip().lower()
    if not email or "@" not in email or any(ch.isspace() for ch in email):
        return None
    return email


def sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def parse_expires(raw: str | None) -> str | None:
    if raw is None:
        return None
    text = raw.strip()
    if not text:
        return None
    if not re.fullmatch(r"[0-9T:Z+\-. ]{6,40}", text):
        raise ValueError("expires_at is not a timestamp")
    return text


def load_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames is None:
            raise SystemExit("CSV has no header")
        fields = {name.strip().lower(): name for name in reader.fieldnames}
        for required in ("challenge_id", "code", "buyer_email"):
            if required not in fields:
                raise SystemExit(f"CSV is missing column {required}")
        rows: list[dict[str, str]] = []
        for index, row in enumerate(reader, start=2):
            challenge_id = (row.get(fields["challenge_id"]) or "").strip()
            code_raw = row.get(fields["code"]) or ""
            email_raw = row.get(fields["buyer_email"]) or ""
            expires_raw = None
            if "expires_at" in fields:
                expires_raw = row.get(fields["expires_at"])
            if not UUID.fullmatch(challenge_id):
                raise SystemExit(f"row {index}: challenge_id is not a uuid")
            normalized = normalize_code(code_raw)
            if normalized is None:
                raise SystemExit(f"row {index}: code is not 8–16 of A–Z0–9 after normalize")
            email = fold_email(email_raw)
            if email is None:
                raise SystemExit(f"row {index}: buyer_email is empty or not an email")
            try:
                expires = parse_expires(expires_raw)
            except ValueError:
                raise SystemExit(f"row {index}: expires_at is not a timestamp") from None
            rows.append(
                {
                    "line": str(index),
                    "challenge_id": challenge_id.lower(),
                    "code_hash": hash_code(normalized),
                    "code_hint": normalized[-4:],
                    "buyer_email": email,
                    "expires_at": expires or "",
                }
            )
        return rows


def emit_sql(rows: list[dict[str, str]]) -> str:
    seen: set[tuple[str, str]] = set()
    values: list[str] = []
    for row in rows:
        key = (row["challenge_id"], row["code_hash"])
        if key in seen:
            raise SystemExit(f"row {row['line']}: duplicate code for this challenge")
        seen.add(key)
        expires = "null" if not row["expires_at"] else f"{sql_literal(row['expires_at'])}::timestamptz"
        values.append(
            "  ({challenge}, {hash}, {hint}, {email}, {expires}, 'vyslapni_cz', 'csv-import')".format(
                challenge=sql_literal(row["challenge_id"]),
                hash=sql_literal(row["code_hash"]),
                hint=sql_literal(row["code_hint"]),
                email=sql_literal(row["buyer_email"]),
                expires=expires,
            )
        )
    body = ",\n".join(values)
    return (
        "-- Generated by scripts/import_redemption_codes.py\n"
        "-- Hash only. Do not apply to production until Ondřej says so.\n"
        "begin;\n"
        "insert into public.challenge_redemption_codes\n"
        "  (challenge_id, code_hash, code_hint, buyer_email, expires_at, source, created_by)\n"
        "values\n"
        f"{body};\n"
        "commit;\n"
    )


def self_test() -> None:
    normalized = normalize_code("  ab12-cd34 ")
    if normalized != "AB12CD34":
        raise SystemExit(f"normalize failed: {normalized}")
    digest = hash_code("AB12CD34")
    if digest != VECTOR:
        raise SystemExit(f"hash mismatch: {digest}")
    if normalize_code("short") is not None:
        raise SystemExit("short code should fail")
    if fold_email("  Ada@Example.com ") != "ada@example.com":
        raise SystemExit("email fold failed")


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", nargs="?", type=Path, help="CSV file to hash")
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="Check normalize and the SHA-256 vector, then exit",
    )
    args = parser.parse_args(argv)
    if args.self_test:
        self_test()
        print("ok")
        return 0
    if args.csv is None:
        parser.error("pass a CSV path, or --self-test")
    sql = emit_sql(load_rows(args.csv))
    sys.stdout.write(sql)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
